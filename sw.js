// Service Worker Absensi Siswa — membuat aplikasi bisa dibuka tanpa internet
// setelah kunjungan pertama. Strategi: cache-first untuk berkas satu origin.
const CACHE = 'absensi-siswa-v4';
const APP_SHELL = [
  './',
  'index.html',
  'qrcode.js',
  'jsQR.js',
  'manifest.webmanifest',
  'icon-192.png',
  'icon-512.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  // Hanya tangani origin sendiri; permintaan luar (mis. Google Fonts) lewat jaringan biasa.
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.match(event.request, { ignoreSearch: true }).then((cached) => {
      if (cached) return cached;
      return fetch(event.request)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put(event.request, copy));
          return res;
        })
        .catch(() => caches.match('index.html'));
    })
  );
});
